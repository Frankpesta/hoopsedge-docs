"""Writes the evidence report: Markdown for reading, JSON for the dashboard, PNG diagrams."""

import json
from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

SERIES = "#2a78d6"
REFERENCE = "#8a8984"
SURFACE = "#fcfcfb"
TEXT = "#0b0b0b"
MUTED = "#52514e"
GRID = "#e6e5e0"
MIN_CHART_ROWS = 30
FAMILY_NAMES = {
    "handicap": "Handicap",
    "total_ft": "Full-time O/U",
    "total_1h": "Half-time O/U",
    "team_total": "Team O/U",
}
SOURCE_NAMES = {"real": "real market lines", "synthetic": "shared synthetic lines"}


def _interval(value: dict[str, Any] | None) -> str:
    if not value:
        return "n/a"
    return f"{value['mean']:+.4f} ({value['low']:+.4f} to {value['high']:+.4f})"


def _table(headers: list[str], rows: list[list[Any]]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return lines


def reliability_chart(rows: list[dict[str, Any]], family: str, source: str, path: Path) -> None:
    """Predicted probability against hit rate. Dot area shows how many rows back each bin."""
    chosen = [
        r
        for r in rows
        if r["family"] == family and r["source"] == source and r["rows"] >= MIN_CHART_ROWS
    ]
    if not chosen:
        return
    figure, axis = plt.subplots(figsize=(5.2, 5.2), dpi=150, facecolor=SURFACE)
    axis.set_facecolor(SURFACE)
    axis.plot([0, 1], [0, 1], color=REFERENCE, linewidth=1, linestyle=(0, (4, 3)))
    axis.text(0.72, 0.62, "perfectly calibrated", color=MUTED, fontsize=8, ha="left")
    figure.text(
        0.02,
        0.005,
        f"Dot area shows rows in the bin. Bins under {MIN_CHART_ROWS} rows are left out; "
        "see the table.",
        color=MUTED,
        fontsize=7,
    )
    largest = max(r["rows"] for r in chosen)
    axis.plot(
        [r["mean_p"] for r in chosen],
        [r["hit_rate"] for r in chosen],
        color=SERIES,
        linewidth=2,
        solid_capstyle="round",
        zorder=2,
    )
    axis.scatter(
        [r["mean_p"] for r in chosen],
        [r["hit_rate"] for r in chosen],
        s=[max(64, 300 * r["rows"] / largest) for r in chosen],
        color=SERIES,
        edgecolors=SURFACE,
        linewidths=2,
        zorder=3,
    )
    axis.set_xlim(0, 1)
    axis.set_ylim(0, 1)
    axis.set_aspect("equal")
    axis.set_xlabel("Predicted probability (calibrated)", color=MUTED, fontsize=9)
    axis.set_ylabel("Actual hit rate", color=MUTED, fontsize=9)
    axis.set_title(
        f"{FAMILY_NAMES[family]}, {SOURCE_NAMES[source]}",
        color=TEXT,
        fontsize=11,
        loc="left",
    )
    axis.grid(color=GRID, linewidth=0.8)
    axis.tick_params(colors=MUTED, labelsize=8, length=0)
    for spine in axis.spines.values():
        spine.set_visible(False)
    figure.tight_layout()
    figure.savefig(path, facecolor=SURFACE)
    plt.close(figure)


def verdict_lines(league: str, gates: dict[str, dict[str, Any]]) -> list[str]:
    lines: list[str] = []
    for family, gate in gates.items():
        name = FAMILY_NAMES[family]
        where = SOURCE_NAMES[gate["judged_on"]]
        if gate["passed"]:
            sentence = f"beats baselines with CI excluding zero, on {where}."
        else:
            sentence = f"does not beat baselines, on {where}."
            if gate["enabled"]:
                sentence += f" Enabled anyway by owner override ({gate['override']['decision']})."
            else:
                sentence += " It's disabled by default."
        if gate["passed"] and gate["edge"] == "unproven":
            sentence += (
                " Its edge over the market is unproven: history has no real lines for it (D18)."
            )
        lines.append(f"- **{league} {name}:** {sentence} Gain: {_interval(gate['gain'])}.")
    return lines


def write_report(result: dict[str, Any], report_dir: Path, today: str) -> Path:
    league = result["league"]
    stem = f"evidence-{league}-{today}"
    report_dir.mkdir(parents=True, exist_ok=True)
    (report_dir / f"{stem}.json").write_text(
        json.dumps(result, indent=1, sort_keys=True) + "\n", "utf-8"
    )

    charts: list[tuple[str, str]] = []
    for family in FAMILY_NAMES:
        for source in SOURCE_NAMES:
            name = f"{stem}-reliability-{family}-{source}.png"
            reliability_chart(result["reliability"], family, source, report_dir / name)
            if (report_dir / name).exists():
                charts.append((f"{FAMILY_NAMES[family]}, {SOURCE_NAMES[source]}", name))

    out = [f"# Evidence: {league}", "", f"Generated by `hoopsedge.backtest.run` on {today}."]
    out += ["", "## Verdict", "", *verdict_lines(league, result["gates"])]
    out += [
        "",
        "A positive gain means the calibrated model has lower log loss than the ratings baseline "
        "on the same games and lines, taking the baseline raw or calibrated, whichever scored "
        "better. Intervals are 95% and resample whole games. The gate only "
        "compares the model with that baseline. Beating it isn't the same as beating the market, "
        "which the market comparison below measures.",
    ]

    out += ["", "## Data", ""]
    out += _table(
        ["Period", "Games", "With a closing line"],
        [[r["label"], r["games"], r["closing_lines"]] for r in result["coverage"]],
    )
    out += ["", *[f"- {note}" for note in result["notes"]]]

    out += ["", "## Score models, all tested games", ""]
    out += _table(
        ["Period", "Target", "Candidate", "Games", "MAE", "RMSE", "CRPS", "Log-lik.",
         "Log-lik. gain vs baseline"],
        [
            [r["period"], r["target"], r["model"], r["games"], r["mae"], r["rmse"], r["crps"],
             r["log_likelihood"], _interval(r["ll_gain_vs_baseline"])]
            for r in result["scores"]
        ],
    )  # fmt: skip

    out += ["", "### By evidence period", ""]
    out += _table(
        ["Evidence period", "Period", "Target", "Candidate", "Games", "MAE", "CRPS"],
        [
            [label, r["period"], r["target"], r["model"], r["games"], r["mae"], r["crps"]]
            for label, table in result["scores_by_label"].items()
            for r in table
        ],
    )

    out += ["", "## Markets", ""]
    out += _table(
        ["Market", "Lines", "Candidate", "Rows", "Log loss raw", "Log loss calibrated", "Brier",
         "Gain vs best baseline"],
        [
            [FAMILY_NAMES[r["family"]], r["source"], r["model"], r["rows"], r["log_loss_raw"],
             r["log_loss_calibrated"], r["brier_calibrated"],
             _interval(r["gain_vs_best_baseline"])]
            for r in result["markets"]
        ],
    )  # fmt: skip

    out += ["", "## Against the market", ""]
    out += _table(
        ["Candidate", "Games", "Margin MAE", "Market", "Gain over market", "Total MAE", "Market",
         "Gain over market"],
        [
            [r["model"], r["games"], r["margin_mae"], r["market_margin_mae"],
             _interval(r["margin_gain_over_market"]), r["total_mae"], r["market_total_mae"],
             _interval(r["total_gain_over_market"])]
            for r in result["market_lines"]
        ],
    )  # fmt: skip
    out += ["", "### Picks passing the thresholds, on real lines", ""]
    if result["selection"]:
        out += _table(
            ["Market", "Candidate", "Picks", "Mean predicted", "Hit rate", "Flat return at -110"],
            [
                [FAMILY_NAMES[r["family"]], r["model"], r["picks"], r.get("mean_p", "n/a"),
                 _interval(r.get("hit_rate")), _interval(r.get("flat_return_at_minus_110"))]
                for r in result["selection"]
            ],
        )  # fmt: skip
    else:
        out += ["None: no market with real lines has a threshold that met the leg floor."]
    out += ["", "Break-even at -110 is a 52.4% hit rate."]

    out += ["", "## Thresholds, chosen on validation only", ""]
    out += _table(
        ["Market", "min_prob", "min_edge", "Legs per slate"],
        [
            [FAMILY_NAMES[family], t["min_prob"], t["min_edge"], t["legs_per_slate"]]
            if t
            else [FAMILY_NAMES[family], "none met the leg floor", "", ""]
            for family, t in result["thresholds"].items()
        ],
    )

    out += ["", "## Early season", ""]
    for title, key in (("All games", "early_all"), ("Games with a real line", "early_priced")):
        out += [f"### {title}", ""]
        out += _table(
            ["Bucket", "Candidate", "Games", "Margin MAE", "Margin bias", "Total MAE",
             "Total bias"],
            [
                [r["bucket"], r["model"], r["games"], r["margin_mae"], r["margin_bias"],
                 r["total_mae"], r["total_bias"]]
                for r in result[key]
            ],
        )  # fmt: skip
        out += [""]

    out += ["## Hit rate by probability bucket", ""]
    out += _table(
        ["Market", "Lines", "Bin", "Rows", "Mean predicted", "Hit rate"],
        [
            [FAMILY_NAMES[r["family"]], r["source"], f"{r['low']}-{r['high']}", r["rows"],
             r["mean_p"], r["hit_rate"]]
            for r in result["reliability"]
        ],
    )  # fmt: skip
    out += ["", "## Reliability diagrams", ""]
    for title, name in charts:
        out += [f"![{title}]({name})", ""]

    out += ["## Distribution form, chosen on validation only", ""]
    forms = result["forms"]
    mixture_note = (
        " It passed on validation, but only the absorbed form is implemented (D68)."
        if forms["overtime_mixture"]["adopt"]
        else ""
    )
    out += [
        f"- Distribution: **{forms['distribution']}**. Empirical CRPS gain: margin "
        f"{forms['empirical']['margin']['gain']:+.4f} ({forms['empirical']['margin']['low']:+.4f} "
        f"to {forms['empirical']['margin']['high']:+.4f}), total "
        f"{forms['empirical']['total']['gain']:+.4f} ({forms['empirical']['total']['low']:+.4f} "
        f"to {forms['empirical']['total']['high']:+.4f}).",
        f"- Overtime: **absorbed in the means**. Mixture log-likelihood gain on totals "
        f"{forms['overtime_mixture']['gain']:+.5f} ({forms['overtime_mixture']['low']:+.5f} to "
        f"{forms['overtime_mixture']['high']:+.5f}), with overtime adding "
        f"{forms['overtime_extra_points']} points.{mixture_note}",
        "",
    ]

    out += ["## Feature importance, full-game home points", ""]
    out += _table(
        ["Feature", "Gain share", "Mean absolute SHAP (points)"],
        [[r["feature"], r["gain_share"], r["shap"]] for r in result["importance"]],
    )
    out += ["", "## Model", "", f"Artifact version: `{result['version']}`."]
    report = report_dir / f"{stem}.md"
    report.write_text("\n".join(out) + "\n", "utf-8")
    return report
